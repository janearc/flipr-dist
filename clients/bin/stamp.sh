#!/bin/sh
# stamp.sh -- the values a build embeds so a client announces which client
# it is: X-Flipr-Client: <lang>/<tag>/<hash> (clients/CONTRACT.md sections 1
# and 8). The hash is the first twelve hex digits of the sha256 over the
# client's own source at the tag, so a copy that was edited hashes
# differently and a build from a tag hashes the same on every machine.
#
#   clients/bin/stamp.sh go          -> the -ldflags value for a Go build
#   clients/bin/stamp.sh typescript  -> FLIPR_CLIENT_TAG=... FLIPR_CLIENT_HASH=... for the package build
#   clients/bin/stamp.sh python      -> the same, for the wheel build
#
# The tag is the newest client-<lang>/v* tag reachable from HEAD, or "dev"
# when there is none, which is what an untagged checkout is.
set -eu
lang="${1:-}"
case "$lang" in go|typescript|python) ;; *) echo "usage: stamp.sh go|typescript|python [--write] [--tag vX.Y.Z]" >&2; exit 2 ;; esac
# --tag names the tag a release is about to cut, so the stamp can be written
# and committed BEFORE the tag exists (the release order in CONTRACT.md 13)
explicit=""
if [ "${2:-}" = "--tag" ]; then explicit="${3:-}"; shift 2; fi
if [ "${3:-}" = "--tag" ]; then explicit="${4:-}"; fi
here="$(cd "$(dirname "$0")/.." && pwd)"
short=go; [ "$lang" = typescript ] && short=ts; [ "$lang" = python ] && short=py
# the Go module's tag follows the go command's rule for a nested module,
# clients/go/vX.Y.Z; the others are client-<short>/vX.Y.Z
pattern="client-$short/v*"; prefix="client-$short/"
[ "$lang" = go ] && pattern="clients/go/v*" && prefix="clients/go/"
tag="$(git -C "$here" describe --tags --match "$pattern" --abbrev=0 2>/dev/null || true)"
tag="${tag#$prefix}"; tag="${explicit:-${tag:-dev}}"
case "$lang" in
  go)         files="$here/go/flipr.go $here/go/retry.go" ;;
  typescript) files="$here/typescript/flipr.ts" ;;
  python)     files="$here/python/flipr_client/_client.py $here/python/flipr_client/_net.py" ;;
esac
# shellcheck disable=SC2086
hash="$(cat $files | shasum -a 256 | cut -c1-12)"
case "$lang" in
  go) echo "-X github.com/janearc/flipr-dist/clients/go.ClientTag=$tag -X github.com/janearc/flipr-dist/clients/go.ClientHash=$hash" ;;
  *)  echo "FLIPR_CLIENT_TAG=$tag FLIPR_CLIENT_HASH=$hash" ;;
esac
# --write regenerates the committed stamp module. All three clients commit
# one: a consumer that pins the tag then announces the tag without passing
# anything at build (found 2026-09-06: no Go consumer passed the -ldflags,
# so every one announced go/dev/unknown). For Go the -ldflags line still
# wins over the committed values when a build passes it.
if [ "${2:-}" = "--write" ]; then
  # a stamp written without --tag is the between-tags one, dev/unknown, so
  # a checkout that moved past a tag does not commit a stamp claiming it
  # (CONTRACT.md 13); the print form above still derives the tag for a
  # build that passes it explicitly
  if [ -z "$explicit" ]; then tag=dev; hash=unknown; fi
  case "$lang" in
    go) printf '%s\n' \
      "package flipr" \
      "" \
      "// stamp.go -- GENERATED by clients/bin/stamp.sh at release; committed as" \
      "// dev/unknown between tags so a checkout announces itself as one" \
      "// (CONTRACT.md section 8). Do not edit; clients/bin/stamp.sh go --write" \
      "// regenerates it. A build's -ldflags -X on these two names still wins." \
      "" \
      "// ClientTag and ClientHash identify this client on the wire as" \
      "// X-Flipr-Client: go/<tag>/<hash>: the tag this source was released at and" \
      "// the first twelve hex digits of the sha256 over flipr.go and retry.go there." \
      "var (" \
      "	ClientTag  = \"$tag\"" \
      "	ClientHash = \"$hash\"" \
      ")" > "$here/go/stamp.go" ;;
    typescript) printf '%s\n' \
      "// stamp.ts -- GENERATED by clients/bin/stamp.sh at package build; committed" \
      "// as dev/unknown so a checkout announces itself as one (CONTRACT.md" \
      "// section 8). Do not edit; clients/bin/stamp.sh typescript --write regenerates it." \
      "export const STAMP = { tag: \"$tag\", hash: \"$hash\" } as const;" > "$here/typescript/stamp.ts" ;;
    python) printf '%s\n' \
      "# _stamp.py -- GENERATED by clients/bin/stamp.sh at package build; committed" \
      "# as dev/unknown so a checkout announces itself as one (CONTRACT.md" \
      "# section 8). Do not edit; clients/bin/stamp.sh python --write regenerates it." \
      "CLIENT_TAG = \"$tag\"" \
      "CLIENT_HASH = \"$hash\"" > "$here/python/flipr_client/_stamp.py" ;;
  esac
fi
